-- MariaDB application schema. Apply explicitly with npm run db:init.
-- Existing tables/data are never replaced by this additive bootstrap.

CREATE TABLE IF NOT EXISTS `User` (
  `id` INT NOT NULL AUTO_INCREMENT,
  `email` VARCHAR(191) NOT NULL,
  `password` VARCHAR(191) NULL,
  `name` VARCHAR(191) NOT NULL,
  `avatar` VARCHAR(191) NOT NULL DEFAULT '',
  `phone` VARCHAR(191) NOT NULL DEFAULT '',
  `googleId` VARCHAR(191) NULL,
  `authProvider` VARCHAR(191) NOT NULL DEFAULT 'local',
  `isVerified` BOOLEAN NOT NULL DEFAULT false,
  `role` VARCHAR(191) NOT NULL DEFAULT 'user',
  `status` VARCHAR(191) NOT NULL DEFAULT 'active',
  `activeToken` TEXT NULL,
  `resetToken` VARCHAR(191) NULL,
  `resetTokenExpires` DATETIME(3) NULL,
  `lastLoginAt` DATETIME(3) NULL,
  `lastLoginIp` VARCHAR(191) NOT NULL DEFAULT '',
  `subPlanId` INT NULL,
  `subPlanSlug` VARCHAR(191) NOT NULL DEFAULT 'free',
  `subStatus` VARCHAR(191) NOT NULL DEFAULT 'active',
  `subStartedAt` DATETIME(3) NULL,
  `subExpiresAt` DATETIME(3) NULL,
  `subAutoRenew` BOOLEAN NOT NULL DEFAULT true,
  `queuedPlanId` INT NULL,
  `queuedPlanSlug` VARCHAR(191) NULL,
  `queuedBillingCycle` VARCHAR(191) NULL,
  `queuedAmount` DOUBLE NULL,
  `queuedStatus` VARCHAR(191) NULL,
  `queuedPurchasedAt` DATETIME(3) NULL,
  `otpCode` VARCHAR(191) NULL,
  `otpExpiresAt` DATETIME(3) NULL,
  `otpPurpose` VARCHAR(191) NULL,
  `oddsFormat` VARCHAR(191) NOT NULL DEFAULT 'decimal',
  `language` VARCHAR(191) NOT NULL DEFAULT 'en',
  `notifEmail` BOOLEAN NOT NULL DEFAULT true,
  `telegramId` VARCHAR(191) NULL,
  `telegramUsername` VARCHAR(191) NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `User_email_key` (`email`),
  UNIQUE KEY `User_googleId_key` (`googleId`),
  KEY `User_role_status_idx` (`role`, `status`),
  KEY `User_subPlanSlug_idx` (`subPlanSlug`),
  KEY `User_subExpiresAt_idx` (`subExpiresAt`),
  KEY `User_status_idx` (`status`),
  KEY `User_resetToken_idx` (`resetToken`)
) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `SubscriptionPlan` (
  `id` INT NOT NULL AUTO_INCREMENT,
  `slug` VARCHAR(191) NOT NULL,
  `name` VARCHAR(191) NOT NULL,
  `description` VARCHAR(191) NOT NULL DEFAULT '',
  `price` INT NOT NULL,
  `yearlyPrice` INT NOT NULL,
  `currency` VARCHAR(191) NOT NULL DEFAULT 'INR',
  `features` JSON NOT NULL,
  `maxMarketsTracked` INT NOT NULL DEFAULT 5,
  `apiCallsPerMin` INT NOT NULL DEFAULT 10,
  `advancedAnalytics` BOOLEAN NOT NULL DEFAULT false,
  `bookieBookAccess` BOOLEAN NOT NULL DEFAULT false,
  `predictionEngine` BOOLEAN NOT NULL DEFAULT false,
  `oddsAlerts` BOOLEAN NOT NULL DEFAULT false,
  `telegramNotifications` BOOLEAN NOT NULL DEFAULT false,
  `isActive` BOOLEAN NOT NULL DEFAULT true,
  `displayOrder` INT NOT NULL DEFAULT 0,
  `createdBy` INT NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `SubscriptionPlan_slug_key` (`slug`),
  KEY `SubscriptionPlan_isActive_displayOrder_idx` (`isActive`, `displayOrder`),
  CONSTRAINT `SubscriptionPlan_createdBy_fkey` FOREIGN KEY (`createdBy`) REFERENCES `User` (`id`) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

