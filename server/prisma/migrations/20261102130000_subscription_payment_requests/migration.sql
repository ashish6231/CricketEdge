CREATE TABLE IF NOT EXISTS `SubscriptionPaymentRequest` (
  `id` INT NOT NULL AUTO_INCREMENT,
  `userId` INT NOT NULL,
  `email` VARCHAR(191) NOT NULL,
  `planId` INT NOT NULL,
  `planSlug` VARCHAR(191) NOT NULL,
  `planName` VARCHAR(191) NOT NULL,
  `billingCycle` VARCHAR(191) NOT NULL,
  `amount` INT NOT NULL,
  `currency` VARCHAR(191) NOT NULL DEFAULT 'INR',
  `utr` VARCHAR(40) NOT NULL,
  `status` VARCHAR(191) NOT NULL DEFAULT 'pending',
  `reviewedById` INT NULL,
  `reviewReason` VARCHAR(500) NOT NULL DEFAULT '',
  `reviewedAt` DATETIME(3) NULL,
  `subscriptionId` INT NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `SubscriptionPaymentRequest_utr_key` (`utr`),
  UNIQUE KEY `SubscriptionPaymentRequest_subscriptionId_key` (`subscriptionId`),
  KEY `SubscriptionPaymentRequest_status_createdAt_idx` (`status`, `createdAt`),
  KEY `SubscriptionPaymentRequest_userId_createdAt_idx` (`userId`, `createdAt`),
  CONSTRAINT `SubscriptionPaymentRequest_userId_fkey` FOREIGN KEY (`userId`) REFERENCES `User` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `SubscriptionPaymentRequest_planId_fkey` FOREIGN KEY (`planId`) REFERENCES `SubscriptionPlan` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `SubscriptionPaymentRequest_reviewedById_fkey` FOREIGN KEY (`reviewedById`) REFERENCES `User` (`id`) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT `SubscriptionPaymentRequest_subscriptionId_fkey` FOREIGN KEY (`subscriptionId`) REFERENCES `UserSubscription` (`id`) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
